/**
 * 根据顾客台词自动匹配一条店主幽默回复。
 *
 * 匹配逻辑：
 * 1. 遍历关键词主题，顾客台词命中任意关键词即从该主题池随机选
 * 2. 多个主题都命中时，取第一个命中的主题
 * 3. 都没命中时，从通用库随机选
 *
 * @param customerText 顾客说的话
 * @returns 店主的幽默回复
 */
export function pickHumorReply(customerText: string): string {
  if (!customerText) {
    return GENERIC_REPLIES[Math.floor(Math.random() * GENERIC_REPLIES.length)];
  }

  for (const group of KEYWORD_REPLIES) {
    if (group.keywords.some(kw => customerText.includes(kw))) {
      return group.replies[Math.floor(Math.random() * group.replies.length)];
    }
  }

  return GENERIC_REPLIES[Math.floor(Math.random() * GENERIC_REPLIES.length)];
}
